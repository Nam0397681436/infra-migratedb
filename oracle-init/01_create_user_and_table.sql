WHENEVER SQLERROR EXIT FAILURE;

ALTER SESSION SET CONTAINER = XEPDB1;

CREATE USER IMGDATA IDENTIFIED BY Nam12345;

GRANT CREATE SESSION, RESOURCE, UNLIMITED TABLESPACE TO IMGDATA;

CREATE TABLE IMGDATA.IMAGES (
   CCCD        VARCHAR2(20)    NOT NULL,
   FILENAME    VARCHAR2(255)   NOT NULL,
   CREATEDAT   TIMESTAMP       DEFAULT SYSTIMESTAMP,
   CONTENTIMG  BLOB,
   CONSTRAINT PK_IMAGES PRIMARY KEY (CCCD)
);
